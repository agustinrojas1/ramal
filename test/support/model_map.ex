defmodule Ramal.ModelMap do
  @moduledoc false
  # Keeps the formal models (verification/) and the code they model from drifting apart unnoticed (ADR 0050).
  #
  # `verification/model_map.exs` says, for every step of every TLA+ model, which functions of lib/ it models. This module
  # reads that map and the code and answers four questions the test in test/ramal/model_map_test.exs turns into failures:
  #
  #   * does every function the map names, and every function a .tla file cites, exist?
  #   * is every step the map names defined in its model?
  #   * is every file under lib/ either read by a model (it holds a modelled function) or listed with the reason
  #     no model reads it?
  #   * has a modelled function changed since someone last checked its step against it? Each step has a stamp in
  #     `verification/model_map.stamps`: a hash of the syntax trees of its functions, with positions, comments, docs
  #     and formatting left out. A stamp that differs means the code of the step changed; whoever changed it reads the
  #     step, edits the model when the rule changed, and runs `STAMP=1 mix test test/ramal/model_map_test.exs`.
  #
  # Only the syntax tree is hashed, so a comment, a @doc or a `mix format` never asks for a re-check, and a renamed
  # variable, a reordered clause or a new line of code always does.

  @root Path.expand("../..", __DIR__)
  @map_file Path.join(@root, "verification/model_map.exs")
  @stamps_file Path.join(@root, "verification/model_map.stamps")
  @models_dir Path.join(@root, "verification/tla")

  @type step :: %{model: String.t(), step: String.t(), code: [String.t()], why: String.t()}
  @type map_data :: %{steps: [step], not_modelled: %{String.t() => String.t()}}

  @doc "The map: the steps of each model with the code they stand for, and the files under lib/ no model reads."
  @spec load() :: map_data
  def load do
    {data, _bindings} = Code.eval_file(@map_file)
    data
  end

  @doc "The stamps stored in the repository: step id => hash."
  @spec stored_stamps() :: %{String.t() => String.t()}
  def stored_stamps do
    case File.read(@stamps_file) do
      {:ok, text} ->
        for line <- String.split(text, "\n", trim: true),
            not String.starts_with?(line, "#"),
            [id, hash] = String.split(line, "  ", parts: 2),
            into: %{},
            do: {id, hash}

      {:error, _} ->
        %{}
    end
  end

  @doc "The id of a step: the model file's name and the step, as `Ramal.tla:Claim`."
  @spec id(step) :: String.t()
  def id(%{model: model, step: step}), do: "#{Path.basename(model)}:#{step}"

  @doc "The stamps the code has now, for every step of the map."
  @spec current_stamps(map_data) :: %{String.t() => String.t()}
  def current_stamps(%{steps: steps}) do
    index = index_code()
    Map.new(steps, fn step -> {id(step), stamp(step, index)} end)
  end

  @doc "Writes `current_stamps/1` to the stamps file, sorted, so a change shows in review as the lines that moved."
  @spec write_stamps(map_data) :: :ok
  def write_stamps(data) do
    lines =
      data
      |> current_stamps()
      |> Enum.sort()
      |> Enum.map_join("\n", fn {id, hash} -> "#{id}  #{hash}" end)

    File.write!(@stamps_file, """
    # Generated by `STAMP=1 mix test test/ramal/model_map_test.exs`. One line per step of verification/model_map.exs: the
    # hash of the syntax tree of the functions the step models. A line that moved means the code of that step changed, and
    # whoever moved it checked the step in verification/tla against the new code (verification/README.md, ADR 0050).
    #{lines}
    """)
  end

  @doc "Every `Module.fun/arity` the .tla files cite in their comments, with the file that cites it."
  @spec cited() :: [{String.t(), String.t()}]
  def cited do
    for file <- Path.wildcard(Path.join(@models_dir, "*.tla")),
        text = File.read!(file),
        [ref] <- Regex.scan(~r/\b(?:[A-Z][A-Za-z]*\.)+[a-z_]+[?!]?\/\d+/, text),
        uniq: true,
        do: {Path.basename(file), ref}
  end

  @doc "The steps a model file defines: top-level definitions of a .tla file, `def`s and `type`s of a .bend file."
  @spec defined_steps(String.t()) :: MapSet.t(String.t())
  def defined_steps(model) do
    text = File.read!(Path.join(@root, "verification/#{model}"))

    pattern =
      if String.ends_with?(model, ".bend"),
        do: ~r/^(?:def|type)\s+([A-Za-z_][\w.]*)/m,
        else: ~r/^([A-Z][A-Za-z]*)(?:\([^)]*\))?\s*==/m

    pattern
    |> Regex.scan(text, capture: :all_but_first)
    |> List.flatten()
    |> MapSet.new()
  end

  @doc """
  Resolves a reference as the models write it. `Ramal.Branch.Server.commit/1` is exact; the models also write
  `Server.commit/1` or `Ramal.fork/2`, which name the module by its last words.
  """
  @spec resolve(String.t(), %{{module, atom, non_neg_integer} => term}) ::
          {:ok, {module, atom, non_neg_integer}} | :error
  def resolve(ref, index) do
    [path, arity] = String.split(ref, "/")
    parts = String.split(path, ".")
    {fun, mod_parts} = List.pop_at(parts, -1)
    suffix = Enum.join(mod_parts, ".")
    arity = String.to_integer(arity)

    matches =
      for {{mod, name, ar}, _} <- index,
          Atom.to_string(name) == fun,
          ar == arity,
          modname = inspect(mod),
          modname == suffix or String.ends_with?(modname, "." <> suffix),
          do: {mod, name, ar}

    case Enum.uniq(matches) do
      [one] -> {:ok, one}
      [] -> :error
      several -> prefer_exact(several, suffix)
    end
  end

  defp prefer_exact(several, suffix) do
    case Enum.filter(several, fn {mod, _, _} -> inspect(mod) == suffix end) do
      [one] -> {:ok, one}
      _ -> :error
    end
  end

  @doc "The file under lib/ that defines `module`."
  @spec file_of(module, %{{module, atom, non_neg_integer} => term}) :: String.t() | nil
  def file_of(module, index) do
    Enum.find_value(index, fn {{mod, _, _}, {file, _}} -> if mod == module, do: file end)
  end

  @doc "All the lib/ files, relative to the repository."
  @spec lib_files() :: [String.t()]
  def lib_files do
    Path.join(@root, "lib/**/*.ex")
    |> Path.wildcard()
    |> Enum.map(&Path.relative_to(&1, @root))
    |> Enum.sort()
  end

  @doc """
  Every function the code defines: `{module, name, arity} => {file, [normalized clause]}`. A function with default
  arguments is indexed under each arity it can be called with.
  """
  @spec index_code() :: %{{module, atom, non_neg_integer} => {String.t(), [Macro.t()]}}
  def index_code do
    lib_files()
    |> Enum.flat_map(&functions_of/1)
    |> Enum.group_by(fn {key, _file, _ast} -> key end, fn {_key, file, ast} -> {file, ast} end)
    |> Map.new(fn {key, clauses} ->
      {file, _} = hd(clauses)
      {key, {file, Enum.map(clauses, &elem(&1, 1))}}
    end)
  end

  defp functions_of(file) do
    ast =
      file
      |> Path.expand(@root)
      |> File.read!()
      |> Code.string_to_quoted!(columns: false, token_metadata: false)

    collect(ast, nil, file)
  end

  defp collect({:defmodule, _, [{:__aliases__, _, parts}, [do: body]]}, parent, file) do
    mod = Module.concat(if(parent, do: [parent | parts], else: parts))
    collect(body, mod, file)
  end

  defp collect({:__block__, _, exprs}, mod, file),
    do: Enum.flat_map(exprs, &collect(&1, mod, file))

  # A module that is only defined when an optional dependency is loaded (Ramal.Storage.Postgres).
  defp collect({:if, _, [_condition, [do: body]]}, mod, file), do: collect(body, mod, file)

  # A behaviour's callback is the contract its implementations keep, which the models cite as `Storage.put/2`.
  defp collect(
         {:@, _, [{:callback, _, [{:"::", _, [{name, _, args}, _return]}] = spec}]},
         mod,
         file
       )
       when is_atom(name) and is_list(args) and mod != nil do
    [{{mod, name, length(args)}, file, strip({:callback, [], spec})}]
  end

  defp collect({kind, _, [head, _body]} = def_ast, mod, file)
       when kind in [:def, :defp] and mod != nil do
    definition(head, def_ast, mod, file)
  end

  # `def f(x)` with no body is a head for a clause that follows.
  defp collect({kind, _, [_head]}, _mod, _file) when kind in [:def, :defp], do: []
  defp collect(_other, _mod, _file), do: []

  defp definition({:when, _, [head | _guards]}, def_ast, mod, file),
    do: definition(head, def_ast, mod, file)

  defp definition({name, _, args}, def_ast, mod, file) when is_atom(name) and is_list(args) do
    defaults = Enum.count(args, &match?({:"\\\\", _, _}, &1))
    arity = length(args)
    clause = strip(def_ast)
    for a <- (arity - defaults)..arity, do: {{mod, name, a}, file, clause}
  end

  defp definition(_head, _def_ast, _mod, _file), do: []

  # Positions are what move when lines above a function change; the rest of the tree is the function.
  defp strip(ast), do: Macro.prewalk(ast, &strip_node/1)
  defp strip_node({form, _meta, args}), do: {form, [], args}
  defp strip_node(other), do: other

  defp stamp(%{code: code} = step, index) do
    clauses =
      for ref <- code do
        {:ok, key} = resolve(ref, index)
        {_file, clauses} = Map.fetch!(index, key)
        {ref, clauses}
      end

    digest = :crypto.hash(:sha256, :erlang.term_to_binary({step.step, clauses}))
    digest |> Base.encode16(case: :lower) |> binary_part(0, 16)
  end
end
